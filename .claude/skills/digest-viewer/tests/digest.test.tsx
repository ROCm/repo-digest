import { expect, test } from 'claude-code/testing'

import { parseDigest, statsLine } from '../hooks/parse'

const SAMPLE = `# XLA Daily Digest - 2026-11-25

## Summary
Big GPU move.

## Key Changes

### 🔴 High Priority
- Move GPU compiler targets by *Alexander Belyaev (Google)* [b6b4c82](https://github.com/openxla/xla/commit/b6b4c82)

    A large restructuring. **ROCm impact:** \`amdgpu_compiler\` moved.

### 🟡 Medium Priority
- Add vectorized exp2 on **XLA:CPU** by *Peter Hawkins (Google)* [281e9b2](https://github.com/openxla/xla/commit/281e9b2)

    CPU only. **ROCm impact:** none expected.

### 🟢 Low Priority
- Drop a redundant conversion in the ROCm tracer test by *xla authors (Google)* [ae6eaa7](https://github.com/openxla/xla/commit/ae6eaa7)

    A one-line cleanup.

## Stats
- **Total Commits**: 3
- **Active Contributors**: 2 (including bots)

---
*Generated by Claude Code.*
`

const digest = parseDigest('downloads/run-1/digest-2026-11-25.md', SAMPLE)

test('parses title, summary, entries and stats', async () => {
  expect(digest.title).toBe('XLA Daily Digest - 2026-11-25')
  expect(digest.runId).toBe('1')
  expect(digest.summary).toBe('Big GPU move.')
  expect(digest.items.map(i => i.priority)).toEqual(['high', 'medium', 'low'])
  expect(digest.items[0]?.sha).toBe('b6b4c82')
  expect(digest.items[0]?.author).toBe('Alexander Belyaev (Google)')
  expect(digest.items.map(i => i.isRocm)).toEqual([true, false, true])
  expect(statsLine(digest.stats)).toBe('Total Commits: 3 · Active Contributors: 2')
})

const PANE = {
  plugin: 'digest-viewer',
  component: 'Pane',
  requestId: 'digest',
  props: {
    title: 'Digest',
    isFocused: false,
    bodyColumns: 80,
    placement: 'dock',
    scroll: { offset: 0, bodyRows: 40 },
    view: {},
  },
} as const

const STORED: Record<string, { shape: string; value: unknown }> = {
  digest: { shape: 'digest-2', value: digest },
  view: {
    shape: 'view-1',
    value: { filter: 'all', isRocmOnly: false, isSummaryOpen: true, expanded: [] },
  },
  library: { shape: 'library-1', value: [digest.path] },
  status: { shape: 'status-1', value: '' },
  runs: { shape: 'runs-1', value: null },
}

test('the pane lists entries, filters, and expands on every surface', async ($, on) => {
  let view = STORED.view!
  let version = 1
  on('state.get', (_, e) => {
    const key = (e as { key: string }).key
    return { value: { value: key === 'view' ? view : STORED[key], version } }
  })
  on('state.set', (_, e) => {
    const set = e as { key: string; value: { shape: string; value: unknown } }
    if (set.key === 'view') view = set.value
    version += 1
    return { value: { isSet: true, version } }
  })

  for (const surface of ['terminal', 'desktop', 'vscode', 'mobile'] as const) {
    view = STORED.view!
    const ui = await $.ui.mount({ ...PANE, surface })
    expect((await ui.find({ type: 'Text', text: /XLA Daily Digest/ }))?.text).toBe(
      'XLA Daily Digest - 2026-11-25',
    )
    expect(await ui.find({ key: '0-b6b4c82' })).toBeDefined()
    expect(await ui.find({ key: '1-281e9b2' })).toBeDefined()

    await ui.press({ key: 'filter-high' })
    expect((view.value as { filter: string }).filter).toBe('high')

    await ui.press({ key: '0-b6b4c82' })
    expect((view.value as { expanded: string[] }).expanded).toEqual(['0-b6b4c82'])
    await ui.unmount()
  }
})

test('older/newer follow GitHub runs and say when a download is needed', async ($, on) => {
  const runs = {
    shape: 'runs-1',
    value: {
      workflowId: 7,
      workflowName: 'Daily XLA Digest',
      checkedAt: 0,
      runs: [
        { id: '2', createdAt: '2026-11-26T08:10:49Z' },
        { id: '1', createdAt: '2026-11-25T08:11:48Z' },
        { id: '0', createdAt: '2026-11-24T08:11:44Z' },
      ],
    },
  }
  on('state.get', (_, e) => {
    const key = (e as { key: string }).key
    return { value: { value: key === 'runs' ? runs : STORED[key], version: 1 } }
  })

  for (const surface of ['terminal', 'desktop'] as const) {
    const ui = await $.ui.mount({ ...PANE, surface })
    // The test has no files, so neither neighbour is local yet.
    expect((await ui.find({ key: 'newer' }))?.text).toContain('Newer · 11-26 (download)')
    expect((await ui.find({ key: 'older' }))?.text).toContain('Older · 11-24 (download)')
    expect(await ui.find({ key: 'close' })).toBeDefined()
    expect(await ui.find({ key: 'check' })).toBeUndefined()
    await ui.unmount()
  }
})
